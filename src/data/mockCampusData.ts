// Generates 248 realistic sensor profiles across 12 buildings
export function generate248Sensors(): Sensor[] {
  const sensorTypes: Array<Sensor['type']> = ['Energy', 'Water', 'Temperature', 'Humidity', 'AQI', 'Noise', 'Occupancy', 'Parking'];
  const protocols: Array<Sensor['protocol']> = ['BACnet/IP', 'LoRaWAN', 'MQTT', 'Modbus'];
  const sensors: Sensor[] = [];

  const buildingSensorsCount: Record<string, number> = {
    'b-main': 22,
    'b-cs': 32,
    'b-sci': 28,
    'b-lib': 20,
    'b-canteen': 18,
    'b-auditorium': 16,
    'b-sports': 14,
    'b-hostel-a': 26,
    'b-hostel-b': 24,
    'b-mech': 18,
    'b-parking': 14,
    'b-utility': 16, // sum = 22+32+28+20+18+16+14+26+24+18+14+16 = 248
  };

  let globalId = 1;
  INITIAL_BUILDINGS.forEach((b) => {
    const count = buildingSensorsCount[b.id] || 20;
    for (let i = 1; i <= count; i++) {
      const type = sensorTypes[i % sensorTypes.length];
      const proto = protocols[i % protocols.length];
      let val = 0;
      let unit = '';
      if (type === 'Energy') { val = Math.round((Math.random() * 8 + 1.2) * 10) / 10; unit = 'kWh'; }
      else if (type === 'Water') { val = Math.round((Math.random() * 25 + 5) * 10) / 10; unit = 'L/min'; }
      else if (type === 'Temperature') { val = Math.round((Math.random() * 5 + 23) * 10) / 10; unit = '°C'; }
      else if (type === 'Humidity') { val = Math.round(Math.random() * 20 + 42); unit = '%'; }
      else if (type === 'AQI') { val = Math.round(Math.random() * 40 + 35); unit = 'AQI'; }
      else if (type === 'Noise') { val = Math.round(Math.random() * 30 + 40); unit = 'dB'; }
      else if (type === 'Occupancy') { val = Math.round(Math.random() * 80 + 10); unit = '%'; }
      else if (type === 'Parking') { val = Math.round(Math.random() * 50 + 10); unit = 'bays'; }

      const isWarning = (b.id === 'b-hostel-a' && type === 'Water' && i === 2) || (b.id === 'b-cs' && type === 'Energy' && i === 4);
      const isOffline = (b.id === 'b-sports' && i === 7) || (b.id === 'b-mech' && i === 5) || (b.id === 'b-sci' && i === 12) || (b.id === 'b-canteen' && i === 9);

      sensors.push({
        id: `SNS-${String(globalId).padStart(4, '0')}`,
        name: `${b.shortName} · ${type} Sensor #${i}`,
        buildingId: b.id,
        buildingName: b.name,
        type,
        value: val,
        unit,
        status: isWarning ? 'warning' : isOffline ? 'offline' : 'online',
        location: `Floor ${Math.floor(i / 5) + 1}, Zone ${String.fromCharCode(65 + (i % 4))}`,
        protocol: proto,
        batteryLevel: proto === 'LoRaWAN' ? Math.round(Math.random() * 30 + 70) : undefined,
        lastPing: `${Math.floor(Math.random() * 5) + 1}s ago`,
      });
      globalId++;
    }
  });

  return sensors;
}
